// ─── Per-Item Progress (Keith's tracking on checklist-1) ─────────────────────

function makePI(
  id: string,
  masterItemId: string,
  toyNumber: string,
  collectorNumber: string,
  modelName: string,
  seriesName: string,
  seriesNumber: string,
  quantityOwned: number,
  isFavorite = false,
  duplicateStatus: DuplicateItemStatus = 'unknown',
): ChecklistProgressItem {
  const owned = quantityOwned > 0;
  const duplicateCount = Math.max(0, quantityOwned - 1);
  const status: ChecklistItemStatus =
    quantityOwned === 0 ? 'need' : quantityOwned === 1 ? 'owned' : 'duplicate';
  return {
    id,
    masterChecklistId: 'mock-checklist-1',
    masterItemId,
    toyNumber,
    collectorNumber,
    modelName,
    seriesName,
    seriesNumber,
    status,
    owned,
    quantityOwned,
    duplicateCount,
    duplicateStatus,
    isFavorite,
    isWanted: false,
    isForSale: false,
    isForTrade: false,
    userNotes: '',
    linkedInventoryCarId: null,
    updatedAt: new Date(),
  };
}

