function makeMI(
  id: string,
  toyNumber: string,
  collectorNumber: string,
  modelName: string,
  seriesName: string,
  seriesNumber: string,
  rarityType: MasterChecklistItem['rarityType'],
  notes = '',
): MasterChecklistItem {
  const sortOrder = parseInt(toyNumber, 10);
  const normalizedSearchText = [modelName, toyNumber, collectorNumber, seriesName, seriesNumber]
    .join(' ')
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '');
  return {
    id,
    toyNumber,
    collectorNumber,
    modelName,
    seriesName,
    seriesNumber,
    photoUrl: null,
    imageRef: null,
    variationLabel: '',
    rarityType,
    notes,
    sortOrder,
    normalizedSearchText,
    createdAt: new Date('2025-01-01'),
    updatedAt: new Date('2025-01-01'),
  };
}

